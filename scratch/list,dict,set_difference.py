#Adding one value : append()
fruits = ["apple", "mango"]
fruits.append("banana")
print(fruits)

nums = [1,2,3]
nums.append(4)
print(nums)

#adding multiple value : extend()
fruits.extend(["grapes","pomegranate"])
print(fruits)

num2 = [100,200]
num2.extend([300,400])
print(num2)

